"""Export a trained StemNet to C++ and write a reference for the C++ test.
  python export.py [models/stemnet_v2.pt]
Writes dsp/src/StemNetWeights.h (the weights as float arrays) and tests/StemNetReference.h (shares
PyTorch computes for a test signal that the C++ test can regenerate exactly: integer-hashed noise
plus two tones), so dsp/src/StemEQ.cpp can be checked frame by frame."""
import os, sys, numpy as np, torch
from common import NBANDS, LOOKAHEAD, features
from model import StemNet

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')


def arr(name, a):
    a = np.asarray(a, np.float32).ravel()
    body = ',\n'.join(', '.join('%.9gf' % v for v in a[i:i + 8]) for i in range(0, len(a), 8))
    return f'inline constexpr float {name}[{len(a)}] = {{\n{body}\n}};\n'


def test_signal(sr, seconds):
    """Must match testSignal() in tests/test_stemeq.cpp: a 110 Hz tone (left-heavy), a 2.5 kHz tone
    gated on and off every 0.25 s (right-heavy) and white noise from an integer hash, in float32."""
    n = np.arange(int(sr * seconds), dtype=np.int64)
    h = (n * 2654435761 + 12345) % 4294967296                         # Knuth multiplicative hash
    noise = (h.astype(np.float64) / 4294967296.0 - 0.5) * 0.1
    t = n / sr
    tone = 0.3 * np.sin(2 * np.pi * 110.0 * t)
    gate = ((n // int(sr / 4)) % 2).astype(np.float64)
    hi = 0.2 * np.sin(2 * np.pi * 2500.0 * t) * gate
    left = (0.8 * tone + 0.3 * hi + noise).astype(np.float32)
    right = (0.4 * tone + 0.9 * hi + noise).astype(np.float32)
    return np.stack([left, right])


if __name__ == '__main__':
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), 'models', 'stemnet_v2.pt')
    net = StemNet.load(path)
    assert not net.gru.bidirectional and net.gru.num_layers == 1, 'the plug-in runs a causal 1-layer GRU'
    sd = {k: v.detach().numpy() for k, v in net.state_dict().items()}
    nin, hid = sd['norm.weight'].shape[0], sd['conv.weight'].shape[0]
    taps = sd['conv.weight'].shape[2]
    with open(os.path.join(ROOT, 'dsp', 'src', 'StemNetWeights.h'), 'w') as f:
        f.write(f'// Generated by tools/stem/export.py from {os.path.basename(path)} - do not edit.\n#pragma once\n\n')
        f.write('namespace polisher::stemnet {\n\n')
        f.write(f'inline constexpr int kIn = {nin}, kHidden = {hid}, kTaps = {taps}, kBands = {NBANDS}, kStems = 4;\n\n')
        f.write(arr('normW', sd['norm.weight'][:, 0, 0]) + arr('normB', sd['norm.bias']))
        f.write(arr('convW', sd['conv.weight']) + arr('convB', sd['conv.bias']))          # [out][in][tap]
        f.write(arr('gruWih', sd['gru.weight_ih_l0']) + arr('gruWhh', sd['gru.weight_hh_l0']))  # rows r, z, n
        f.write(arr('gruBih', sd['gru.bias_ih_l0']) + arr('gruBhh', sd['gru.bias_hh_l0']))
        f.write(arr('outW', sd['out.weight']) + arr('outB', sd['out.bias']))               # rows stem * kBands + band
        f.write('\n} // namespace polisher::stemnet\n')

    sr, frames = 44100, (100, 200, 300)
    x = test_signal(sr, 2.0)
    feat = features(x, sr)
    with torch.no_grad():
        p = torch.softmax(net(torch.from_numpy(feat[None])), 1)[0].numpy()     # 4, B, F - 2*LOOKAHEAD
    with open(os.path.join(ROOT, 'tests', 'StemNetReference.h'), 'w') as f:
        f.write('// Generated by tools/stem/export.py - do not edit.\n#pragma once\n\n')
        f.write('namespace stemref {\n\n')
        f.write(f'inline constexpr double kSampleRate = {sr};\n')
        f.write(f'inline constexpr int kFrames[{len(frames)}] = {{ {", ".join(map(str, frames))} }};  // centre frame of each output\n')
        f.write('// Features (2 x 64) of each frame above, then the shares [stem][band] PyTorch gives it.\n')
        f.write(arr('features', np.stack([feat[:, k] for k in frames])))
        f.write(arr('shares', np.stack([p[:, :, k - LOOKAHEAD] for k in frames])))
        f.write('\n} // namespace stemref\n')
    print('weights:', sum(v.size for v in sd.values()), 'floats; reference frames', frames)
